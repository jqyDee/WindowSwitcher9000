//
//  ClipboardViewModel.swift
//  WindowSwitcher
//
//  State behind clipboard mode (entered with `#`): watches the system clipboard, records what is
//  copied into the persisted history, and copies entries back. Shared, so the panel, Settings and the
//  always-running watcher use one history.
//

import AppKit
import ClipboardHistory
import Combine
import ImageIO

@MainActor
public final class ClipboardViewModel: ObservableObject {
    public static let shared = ClipboardViewModel()

    private static let historyLimitKey = "ClipboardHistoryLimit"
    public static let defaultHistoryLimit = 30
    public static let historyLimitRange = 10...1000
    /// How often the clipboard is checked: macOS has no change notification, only a change counter.
    private static let pollInterval: TimeInterval = 0.5

    /// Clipboard types apps set to say "don't keep this" (nspasteboard.org, plus the private markers
    /// other clipboard managers honor); such content is never recorded.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "net.antelle.keeweb", "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping", "Pasteboard generator type",
    ].reduce(into: []) { $0.insert(NSPasteboard.PasteboardType($1)) }

    /// Password managers. Not all of them mark what they copy as concealed (Apple's Passwords app doesn't),
    /// so nothing copied while one of them is frontmost is recorded.
    private static let ignoredApps: Set<String> = [
        "com.apple.Passwords", "com.apple.keychainaccess",
        "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "org.keepassxc.keepassxc",
    ]

    private let store: ClipboardStore
    /// Newest first.
    @Published public private(set) var items: [ClipItem] = []
    /// Index into `filteredItems(matching:)` of the current query.
    @Published public var selectedIndex = 0
    /// Most entries kept; lowering it deletes the oldest entries beyond it.
    @Published public var historyLimit: Int {
        didSet {
            UserDefaults.standard.set(historyLimit, forKey: Self.historyLimitKey)
            store.trim(to: historyLimit)
            items = store.items
        }
    }

    private var timer: Timer?
    private var lastChangeCount = -1
    /// Last time a password manager was the frontmost app. Copies shortly after still count as
    /// coming from it: the watcher may only notice a copy after the user switched away.
    private var passwordManagerLastFrontmost = Date.distantPast
    private static let passwordManagerGrace: TimeInterval = 2
    /// The entry recorded last, and when; deleted again if the clipboard is wiped soon after
    /// (password managers clear what they copied, ordinary apps don't).
    private var lastRecorded: (id: ClipItem.ID, at: Date)?
    private static let wipeWindow: TimeInterval = 3 * 60
    private var deactivationObserver: NSObjectProtocol?
    /// The clipboard's change count right after `copy` wrote to it: that change is this app's own,
    /// so it moves the entry to the top without replacing its source app.
    private var ownChangeCount: Int?
    private var thumbnails: [ClipItem.ID: NSImage] = [:]

    private init() {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        store = ClipboardStore(directory: support.appendingPathComponent("WindowSwitcher9000/Clipboard", isDirectory: true))
        let storedLimit = UserDefaults.standard.integer(forKey: Self.historyLimitKey)
        historyLimit = storedLimit > 0 ? storedLimit : Self.defaultHistoryLimit
        items = store.items
    }

    // MARK: - Watching the clipboard

    /// Starts recording what is copied. Runs for the app's lifetime, whether or not the panel is open.
    public func startMonitoring() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: Self.pollInterval, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardViewModel.shared.checkClipboard() }
        }
        deactivationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didDeactivateApplicationNotification, object: nil, queue: .main
        ) { notification in
            let app = notification.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
            guard let bundleID = app?.bundleIdentifier, Self.ignoredApps.contains(bundleID) else { return }
            MainActor.assumeIsolated { ClipboardViewModel.shared.passwordManagerLastFrontmost = .now }
        }
        checkClipboard()
    }

    private func checkClipboard() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        if pasteboard.pasteboardItems?.isEmpty ?? true {
            forgetWipedEntry()
            return
        }
        let frontmost = NSWorkspace.shared.frontmostApplication
        if let bundleID = frontmost?.bundleIdentifier, Self.ignoredApps.contains(bundleID) {
            passwordManagerLastFrontmost = .now
        }
        guard Date.now.timeIntervalSince(passwordManagerLastFrontmost) > Self.passwordManagerGrace else { return }
        guard let content = Self.readContent(from: pasteboard) else { return }

        // an entry copied back from the history keeps its original source
        // (the panel doesn't activate this app, so the frontmost app is the one it was opened over)
        let source = pasteboard.changeCount == ownChangeCount ? nil : frontmost?.localizedName
        let item = store.record(content, sourceApp: source, limit: historyLimit)
        lastRecorded = (item.id, .now)
        items = store.items
    }

    /// The clipboard was emptied. Password managers do that a little while after copying a secret,
    /// so the entry recorded just before is removed: it was most likely a password copied without the
    /// password manager in front (its menu bar item, autofill).
    private func forgetWipedEntry() {
        guard let recorded = lastRecorded, Date.now.timeIntervalSince(recorded.at) < Self.wipeWindow,
              let item = items.first(where: { $0.id == recorded.id }) else { return }
        lastRecorded = nil
        remove(item)
    }

    /// Files first (Finder also puts their icons and names on the clipboard), then text, then images.
    static func readContent(from pasteboard: NSPasteboard) -> ClipContent? {
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: ignoredTypes) else { return nil }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls)
        }
        if let string = pasteboard.string(forType: .string), !string.trimmed.isEmpty {
            return .text(string)
        }
        if let data = pasteboard.data(forType: .png) { return .image(data, format: .png) }
        if let data = pasteboard.data(forType: .tiff) { return .image(data, format: .tiff) }
        return nil
    }

    // MARK: - Using the history

    public func filteredItems(matching query: String) -> [ClipItem] {
        items.filter { $0.matches(query) }
    }

    /// Puts `item` back on the clipboard. The watcher then sees it and moves the entry to the top,
    /// as for anything copied that is already in the history.
    /// Returns a message instead when it can't, leaving the clipboard untouched.
    @discardableResult
    public func copy(_ item: ClipItem, to pasteboard: NSPasteboard = .general) -> String? {
        switch item.kind {
        case .text:
            pasteboard.clearContents()
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            guard let url = store.imageURL(for: item), let data = try? Data(contentsOf: url) else {
                return "The image could not be read"
            }
            pasteboard.clearContents()
            pasteboard.setData(data, forType: url.pathExtension == "png" ? .png : .tiff)
        case .files:
            let urls = item.fileURLs ?? []
            if let error = Self.checkReadable(urls) { return error }
            // the same flavors Finder writes: file URLs, the legacy file name list some apps still read,
            // and the names as text for text fields
            pasteboard.clearContents()
            pasteboard.writeObjects(urls.map { $0 as NSURL })
            let filenames = NSPasteboard.PasteboardType("NSFilenamesPboardType")
            pasteboard.addTypes([filenames, .string], owner: nil)
            pasteboard.setPropertyList(urls.map(\.path), forType: filenames)
            pasteboard.setString(urls.map(\.lastPathComponent).joined(separator: "\n"), forType: .string)
        }
        if pasteboard == .general { ownChangeCount = pasteboard.changeCount }
        return nil
    }

    /// Opens each file once. Other apps can only receive a file through the clipboard if this app can
    /// read it ("Failed sandbox check for path" otherwise), and for protected folders like Desktop,
    /// Documents or Downloads opening it is what makes macOS ask the user for access.
    private static func checkReadable(_ urls: [URL]) -> String? {
        for url in urls {
            guard FileManager.default.fileExists(atPath: url.path) else {
                return "\u{201C}\(url.lastPathComponent)\u{201D} no longer exists"
            }
            let descriptor = open(url.path, O_RDONLY)
            guard descriptor >= 0 else {
                return "No access to \u{201C}\(url.lastPathComponent)\u{201D}: allow it in System Settings → Privacy & Security → Files and Folders"
            }
            close(descriptor)
        }
        return nil
    }

    public func remove(_ item: ClipItem) {
        store.remove(id: item.id)
        thumbnails[item.id] = nil
        items = store.items
    }

    public func clearHistory() {
        store.clear()
        thumbnails = [:]
        items = []
        selectedIndex = 0
    }

    public func moveSelection(by offset: Int, count: Int) {
        guard count > 0 else { return }
        selectedIndex = min(max(selectedIndex + offset, 0), count - 1)
    }

    // MARK: - Images

    public func image(for item: ClipItem) -> NSImage? {
        store.imageURL(for: item).flatMap { NSImage(contentsOf: $0) }
    }

    /// A small, cached version for list rows, so long histories don't decode every full-size image.
    public func thumbnail(for item: ClipItem, size: CGFloat = 64) -> NSImage? {
        if let cached = thumbnails[item.id] { return cached }
        guard let url = store.imageURL(for: item),
              let source = CGImageSourceCreateWithURL(url as CFURL, nil),
              let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                  kCGImageSourceCreateThumbnailFromImageAlways: true,
                  kCGImageSourceThumbnailMaxPixelSize: size * 2,
              ] as CFDictionary) else { return nil }
        let image = NSImage(cgImage: cgImage, size: .zero)
        thumbnails[item.id] = image
        return image
    }
}
